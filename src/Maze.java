    public static char[][] createGrid(int levelIndex) {
        int index = Math.min(levelIndex, LEVELS.length - 1);
        if (index < 0) index = 0;

        String[] data = LEVELS[index];
        char[][] grid = new char[GameConfig.ROWS][];
        for (int r = 0; r < GameConfig.ROWS; r++) {
            grid[r] = data[r].toCharArray();
        }
        return grid;
    }

    public static int countPellets(char[][] grid) {
        int count = 0;
        for (int r = 0; r < GameConfig.ROWS; r++)
            for (int c = 0; c < GameConfig.COLS; c++)
                if (grid[r][c] == '.' || grid[r][c] == 'o') count++;
        return count;
    }
